/* ============================================================================
   tool-previews.js — the video-preview behaviour shared by every tool card.
   ----------------------------------------------------------------------------
   Assets: assets/previews/<slug>.jpg (poster) + <slug>.mp4 (silent, looping).
   Which slugs have a preview is decided at BUILD time, not by probing the
   network from the browser: assets/js/preview_manifest.js (generated by
   _tools/build_preview_manifest.py) lists every slug with both files on disk.
   The old approach set a lazy <img> src and waited for load/error to decide —
   below the fold the browser never issues that request, so the check never
   answered and every off-screen card fell back to the icon tile even where a
   real preview existed. PREVIEW_MEDIA now reads the manifest directly, so the
   markup is right the first time and nothing is ever fetched needlessly.

   Three tiers (Surya's Fix 1, 2026-08-31 — "I need the videos ... to be
   shown [on cards], not [a] pale icon block"):
     1. video   — slug is in PREVIEW_MANIFEST. Poster + hover/scroll video,
                  same as before.
     2. still   — no video, but slug is in STILL_MANIFEST (assets/js/
                  still_manifest.js, hand-curated — see that file for why a
                  screenshot folder existing is not enough on its own). A
                  plain always-visible <img>, no video machinery.
     3. nothing — neither exists. PREVIEW_MEDIA returns '' and the card
                  renders with no top-media block at all: a clean text-only
                  card, not the old tinted icon panel. See browseCard() in
                  home.js for the 'fcard--text' modifier this implies.
   The old kind-tinted '.pv-empty' icon panel is gone in all three cases —
   a smaller honest card beats a big empty-looking one.

   PREVIEW_MEDIA(slug, kind, extraClass) returns the markup a card embeds.
   PREVIEW_INIT() (re)scans the document for '.pv-media[data-preview-slug]'
   nodes and wires them up — call it again after any innerHTML swap that
   added new cards. Still-tier and empty cards carry no such attribute, so
   they are never wired (nothing to wire: no video, no state machine).

   Rules this follows (design brief, 2026-08-31):
   - preload="none" always; the <video> element itself is only created once a
     card is near the viewport or actually hovered, never 52 at once.
   - desktop (hover:hover) plays on mouseenter, pauses+resets on mouseleave.
   - touch (hover:none) plays while the card is in view, pauses when it isn't.
   - at most PLAY_MAX preview videos play at once, globally, across the page.
   - prefers-reduced-motion: poster only, video is never attached.
   - muted + loop + playsinline always; no audio track is ever expected.
   ============================================================================ */
(function () {
  'use strict';

  var PLAY_MAX = 2;
  var PREVIEW_DIR = 'assets/previews/';
  var reduced = window.matchMedia && matchMedia('(prefers-reduced-motion: reduce)').matches;
  var isTouch = window.matchMedia && matchMedia('(hover: none), (pointer: coarse)').matches;

  /* The build-time fact lists. Arrays/objects on window so they survive
     whichever script-load order a page uses; a Set here for O(1) lookups. */
  var PREVIEW_SET = new Set(window.PREVIEW_MANIFEST || []);
  var STILL_MAP = window.STILL_MANIFEST || {};

  /* Per-element state, keyed by the '.pv-media' node so re-scanning never
     double-wires the same card. */
  var state = typeof WeakMap === 'function' ? new WeakMap() : null;
  var seen = [];                       /* fallback for engines with no WeakMap */
  function getState(el) {
    if (state) return state.get(el);
    for (var i = 0; i < seen.length; i++) if (seen[i][0] === el) return seen[i][1];
    return undefined;
  }
  function setState(el, s) {
    if (state) { state.set(el, s); return; }
    seen.push([el, s]);
  }

  var playing = [];                    /* videos currently playing, oldest first */
  function stopVideo(v) {
    if (!v) return;
    try { v.pause(); v.currentTime = 0; } catch (e) { /* not ready yet, fine */ }
    var media = v.closest && v.closest('.pv-media');
    if (media) media.classList.remove('is-playing');
    var idx = playing.indexOf(v);
    if (idx !== -1) playing.splice(idx, 1);
  }
  function reserveSlot(v) {
    while (playing.length >= PLAY_MAX) {
      var oldest = playing[0];
      if (oldest === v) break;
      stopVideo(oldest);
    }
    if (playing.indexOf(v) === -1) playing.push(v);
  }

  /* Creates the <video> the first time a card needs it. Returns null if the
     clip 404s — the poster stays on screen if it loaded, otherwise 'is-empty'
     hides the whole media block (CSS) so the card collapses to the same
     clean text-only shape a build-time no-preview card gets, rather than
     showing a broken/blank box. This only fires if a manifest-listed file
     is missing at runtime — the manifest itself guarantees both exist. */
  function attachVideo(media, s) {
    if (s.video || s.errored || reduced) return s.video;
    var slug = media.getAttribute('data-preview-slug');
    var v = document.createElement('video');
    v.className = 'pv-video';
    v.muted = true; v.loop = true; v.playsInline = true; v.setAttribute('playsinline', '');
    v.preload = 'none';
    v.setAttribute('aria-hidden', 'true');
    v.setAttribute('tabindex', '-1');
    v.addEventListener('error', function () {
      v.remove();
      s.video = null;
      if (!s.hasPoster) media.classList.add('is-empty');
    });
    media.appendChild(v);
    /* Direct .src (not a <source> child) so the resource-selection algorithm
       runs deterministically on assignment, then .play() below both starts
       the fetch (preload="none" defers it until now) and playback. */
    v.src = PREVIEW_DIR + slug + '.mp4';
    s.video = v;
    return v;
  }

  function play(media, s) {
    if (reduced || s.errored) return;
    var v = attachVideo(media, s);
    if (!v) return;
    reserveSlot(v);
    var p = v.play();
    if (p && p.catch) p.catch(function () { /* autoplay refused, poster stays visible */ });
    media.classList.add('is-playing');
  }
  function pause(media, s) {
    if (!s.video) return;
    stopVideo(s.video);
  }

  /* The manifest already guarantees the file exists, so the poster is marked
     present immediately — no waiting on a load event that a below-the-fold
     <img> may never fire. The load/error listeners stay as a belt-and-braces
     fallback for the rare case for a file that is listed but fails to decode. */
  function wirePoster(media, s) {
    var img = media.querySelector('.pv-poster');
    if (!img) return;
    s.hasPoster = true;
    media.classList.add('has-poster');
    img.addEventListener('error', function () {
      s.errored = true; s.hasPoster = false;
      media.classList.remove('has-poster'); media.classList.add('is-empty');
    }, { once: true });
  }

  /* One IO for the whole page. Touch devices use it to drive play/pause;
     desktop only uses it to know a card is close, which matters nothing here
     since hover already implies visibility — it is left running on desktop
     too so the code path is one path, not two. */
  var io = ('IntersectionObserver' in window) ? new IntersectionObserver(function (entries) {
    entries.forEach(function (entry) {
      var media = entry.target;
      var s = getState(media);
      if (!s) return;
      if (isTouch) {
        if (entry.isIntersecting && entry.intersectionRatio >= 0.5) play(media, s);
        else pause(media, s);
      }
    });
  }, { threshold: [0, 0.5], rootMargin: '80px 0px' }) : null;

  function wireCard(media) {
    if (getState(media)) return;                 /* already wired */
    var s = { video: null, errored: false, hasPoster: false };
    setState(media, s);
    wirePoster(media, s);
    if (io) io.observe(media);
    if (!isTouch) {
      /* Hover the whole card, not just the thumbnail strip -- the card is
         one clickable target (an <a>), so the preview should react to the
         same area a visitor would naturally point at. */
      var host = media.closest('a') || media;
      host.addEventListener('mouseenter', function () { play(media, s); });
      host.addEventListener('mouseleave', function () { pause(media, s); });
    }
  }

  /* Only nodes that actually carry a slug (i.e. the video manifest had one)
     need wiring — a still-tier card is a plain <img> with nothing to play,
     and a no-media card has no '.pv-media' node at all. */
  function PREVIEW_INIT() {
    var nodes = document.querySelectorAll('.pv-media[data-preview-slug]');
    for (var i = 0; i < nodes.length; i++) wireCard(nodes[i]);
  }

  /* Markup a card embeds — one of three tiers, see the file header. `kind` is
     accepted for API stability but no longer used to draw an icon here; the
     card's own fc-mark already shows the kind glyph regardless of which tier
     this returns. `extra` adds a size/position modifier class, e.g.
     'pv-media--card'. Which tier applies is a build-time fact (PREVIEW_SET /
     STILL_MAP), so the right markup ships on the first render, nothing is
     fetched needlessly, and a true miss returns '' rather than a filler box —
     home.js's caller is expected to render a clean text-only card when it
     gets '' back (see 'fcard--text' in browseCard()). */
  function PREVIEW_MEDIA(slug, kind, extra) {
    if (!slug) return '';
    var cls = 'pv-media' + (extra ? ' ' + extra : '');
    if (!PREVIEW_SET.has(slug)) {
      var still = STILL_MAP[slug];
      if (!still) return '';
      return '<div class="' + cls + ' is-still">' +
        '<img class="pv-poster" alt="" loading="lazy" decoding="async" src="' + still + '"></div>';
    }
    return '<div class="' + cls + '" data-preview-slug="' + slug + '">' +
      '<img class="pv-poster" alt="" loading="lazy" decoding="async" src="' + PREVIEW_DIR + slug + '.jpg">' +
    '</div>';
  }

  window.PREVIEW_MEDIA = PREVIEW_MEDIA;
  window.PREVIEW_INIT = PREVIEW_INIT;

  document.addEventListener('DOMContentLoaded', PREVIEW_INIT);
})();
